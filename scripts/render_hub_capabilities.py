#!/usr/bin/env python3
"""
render_hub_capabilities.py - writes templates\\hub_capabilities.md from capability_catalog.yaml:
one line per hub-fitting node (context hub or both), trigger plus full description.

Usage:
  python render_hub_capabilities.py          write templates\\hub_capabilities.md
  python render_hub_capabilities.py --check  notify-only; prints [HUB-CAPABILITIES-STALE] when the
                                             file is missing or differs from the catalog

Exit 0 always for a readable catalog; 1 on a missing or unparseable catalog.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_commands

SHARED_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = SHARED_ROOT / 'templates' / 'hub_capabilities.md'

HEADER = """<!--
Generated by scripts\\render_hub_capabilities.py from capability_catalog.yaml. Never hand-edit;
edit a node's `description` in the catalog and rerun the script.
Imported by the hub's outer CLAUDE.md only; consumers do not load it.
-->

## Hub commands and what each one does
"""


def build():
    cat = render_commands.load_catalog(render_commands.DEFAULT_CATALOG)
    lines = [HEADER]
    for node in cat['nodes']:
        if not render_commands.fits(node, 'hub'):
            continue
        desc = ' '.join(str(node.get('description', '')).split())
        lines.append(f"- **{node['trigger']}** — {desc}")
    return '\n'.join(lines) + '\n'


def report_stale():
    try:
        text = build()
    except (OSError, ValueError) as exc:
        print(f"[ERROR] {exc}")
        return 1
    current = OUTPUT.read_text(encoding='utf-8').replace('\r\n', '\n') if OUTPUT.is_file() else None
    if current != text:
        print(f"[HUB-CAPABILITIES-STALE] {OUTPUT} is missing or differs from the catalog - "
              f"run: python toolkit/scripts/render_hub_capabilities.py")
    return 0


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if args.check:
        return report_stale()
    try:
        text = build()
    except (OSError, ValueError) as exc:
        print(f"[ERROR] {exc}")
        return 1
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f"wrote {OUTPUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
